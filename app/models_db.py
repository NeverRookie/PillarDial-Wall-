def get_model_specs(model_id: str = None, custom_width: int = None, custom_height: int = None, custom_clock_ratio: float = None):
    normalized_id = (model_id or "").lower().replace(" ", "").replace("-", "").replace("_", "")
    if normalized_id in IPHONE_MODELS:
        specs = IPHONE_MODELS[normalized_id].copy()
    else:
        specs = IPHONE_MODELS["iphone16"].copy()

    if custom_width and custom_width > 0:
        specs["width"] = int(custom_width)
    if custom_height and custom_height > 0:
        specs["height"] = int(custom_height)
    if custom_clock_ratio and custom_clock_ratio > 0:
        specs["clock_height_ratio"] = float(custom_clock_ratio)

    return specs
